function doc(
  name: string,
  at: string,
  kind: "pdf" | "png" | "jpeg" = "pdf",
  sizeKb = 412,
) {
  return {
    name,
    kind,
    sizeKb,
    uploadedAt: at,
    storagePath: `fdr-documents/${name}`,
  }
}

function make(s: Seed): Fdr {
  return { bankConfirmation: "not_requested", flags: [], events: [], ...s }
}

